import type { ReactNode } from 'react';
import clsx from 'clsx';
import { Sparkles } from 'lucide-react';

export interface AiPanelProps {
  children?: ReactNode;
  /** 0..1 */
  confidence?: number;
  /** ISO date string */
  generatedAt?: string;
  title?: string;
  className?: string;
}

export function AiPanel({ children, confidence, generatedAt, title = 'Simulated AI output', className }: AiPanelProps) {
  let when: string | undefined;
  if (generatedAt) {
    const d = new Date(generatedAt);
    when = Number.isNaN(d.getTime())
      ? generatedAt
      : d.toLocaleString('en-GB', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
  }
  return (
    <section
      aria-label={title}
      className={clsx(
        'rounded-2xl border border-ai-300 bg-ai-50/60 dark:border-ai-800 dark:bg-ai-950/30',
        className,
      )}
    >
      <header className="flex flex-wrap items-center justify-between gap-2 border-b border-ai-200 px-4 py-3 dark:border-ai-900">
        <div className="flex items-center gap-2">
          <span className="flex h-6 w-6 items-center justify-center rounded-lg bg-ai-700 text-white dark:bg-ai-600">
            <Sparkles className="h-3.5 w-3.5" aria-hidden="true" />
          </span>
          <h3 className="text-sm font-semibold text-ai-900 dark:text-ai-200">{title}</h3>
        </div>
        {(confidence !== undefined || when) && (
          <div className="flex items-center gap-3 text-xs text-ai-800 dark:text-ai-300">
            {confidence !== undefined && (
              <span title="Illustrative confidence score from deterministic demo rules">
                Confidence {Math.round(confidence * 100)}%
              </span>
            )}
            {when && <span>Generated {when}</span>}
          </div>
        )}
      </header>
      <div className="px-4 py-3 text-sm text-ink-800 dark:text-ink-200">{children}</div>
      <p className="border-t border-ai-200 px-4 py-2 text-xs text-ai-800 dark:border-ai-900 dark:text-ai-300">
        Generated by deterministic demo rules, not a real AI. Requires human review.
      </p>
    </section>
  );
}
